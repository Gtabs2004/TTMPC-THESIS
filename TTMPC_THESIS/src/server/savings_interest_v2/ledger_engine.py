"""
TTMPC Savings Ledger Interest Engine (draft, v2 — confirmed true cooperative rule, 2026-10-17).

Replaces the "month-end balance, monthly posting" assumption in
SAVINGS_INTEREST_PLAN.md (shelved 2026-10-13) with the cooperative's actual rule:

  - 1.00% per annum nominal rate.
  - Actual/365 day-count.
  - Interest accrues on the RUNNING BALANCE between consecutive ledger lines
    (never on the isolated deposit/withdrawal amount).
  - Accrued interest is capitalized (posted as a credit, Transaction Code
    "Int.") only at calendar quarter-end: Mar 31, Jun 30, Sep 30, Dec 31.
  - A minimum balance threshold (configurable) must be held for a line's
    interval to accrue interest at all.

Not wired into main.py or Supabase yet — see SAVINGS_INTEREST_V2_PLAN.md.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date
from decimal import ROUND_HALF_UP, Decimal
from typing import Optional

ANNUAL_RATE = Decimal("0.01")
DAYS_IN_YEAR = Decimal("365")
TWO_PLACES = Decimal("0.01")

QUARTER_END_MONTHS_DAYS = ((3, 31), (6, 30), (9, 30), (12, 31))


def money(value: Decimal) -> Decimal:
    return value.quantize(TWO_PLACES, rounding=ROUND_HALF_UP)


def is_quarter_end(d: date) -> bool:
    return (d.month, d.day) in QUARTER_END_MONTHS_DAYS


@dataclass
class Transaction:
    """One passbook input row: a deposit or withdrawal. Interest rows are
    generated by the engine, never supplied here."""

    txn_date: date
    code: str  # "CD" or "WD"
    amount: Decimal

    def __post_init__(self) -> None:
        if self.code not in ("CD", "WD"):
            raise ValueError(f"Transaction code must be CD or WD, got {self.code!r}")
        if self.amount <= 0:
            raise ValueError("Transaction amount must be positive")


@dataclass
class LedgerRow:
    """One rendered passbook line, matching the member-facing table columns."""

    date: date
    code: str
    withdrawal: Optional[Decimal] = None
    interest_posted: Optional[Decimal] = None
    deposit: Optional[Decimal] = None
    total_balance: Decimal = Decimal("0")
    accrued_line_interest: Decimal = Decimal("0")


@dataclass
class SavingsLedgerEngine:
    """
    Sequential ledger processor.

    - opening_date / opening_balance: the account's starting point (e.g. the
      most recent prior quarter-close, or account opening).
    - minimum_balance: threshold a line's balance must meet for that
      interval's days to accrue interest. None = no minimum.
    """

    opening_date: date
    opening_balance: Decimal
    minimum_balance: Optional[Decimal] = None

    _rows: list[LedgerRow] = field(default_factory=list, init=False)
    _last_date: date = field(init=False)
    _balance: Decimal = field(init=False)
    _accrued_since_last_post: Decimal = field(init=False, default=Decimal("0"))

    def __post_init__(self) -> None:
        self._last_date = self.opening_date
        self._balance = self.opening_balance

    def _accrue(self, as_of: date, balance: Decimal) -> Decimal:
        """Interest for the interval (self._last_date, as_of] at the given
        (resulting) balance, per the formula:
            days * balance * annual_rate / 365
        Zero if that balance is below the minimum.
        """
        days = (as_of - self._last_date).days
        if days <= 0:
            return Decimal("0")
        if self.minimum_balance is not None and balance < self.minimum_balance:
            return Decimal("0")
        raw = Decimal(days) * balance * ANNUAL_RATE / DAYS_IN_YEAR
        return money(raw)

    def post_transaction(self, txn: Transaction) -> LedgerRow:
        if txn.txn_date < self._last_date:
            raise ValueError(
                f"Transaction date {txn.txn_date} precedes prior ledger date {self._last_date}"
            )

        if txn.code == "CD":
            new_balance = self._balance + txn.amount
        else:  # WD
            if txn.amount > self._balance:
                raise ValueError(
                    f"Withdrawal of {txn.amount} on {txn.txn_date} exceeds balance {self._balance}"
                )
            new_balance = self._balance - txn.amount

        # Spec formula uses the RESULTING balance of the row, not the
        # balance during the interval leading up to it.
        line_interest = self._accrue(txn.txn_date, new_balance)
        self._accrued_since_last_post += line_interest

        self._balance = new_balance
        self._last_date = txn.txn_date

        row = LedgerRow(
            date=txn.txn_date,
            code=txn.code,
            withdrawal=txn.amount if txn.code == "WD" else None,
            deposit=txn.amount if txn.code == "CD" else None,
            total_balance=self._balance,
            accrued_line_interest=line_interest,
        )
        self._rows.append(row)
        return row

    def post_quarter_close(self, as_of: date) -> LedgerRow:
        """Capitalize all interest accrued since the last posting as of
        `as_of` (must be a calendar quarter-end date)."""
        if not is_quarter_end(as_of):
            raise ValueError(f"{as_of} is not a quarter-end date (Mar/Jun/Sep/Dec 31)")
        if as_of < self._last_date:
            raise ValueError(f"Quarter-close {as_of} precedes prior ledger date {self._last_date}")

        line_interest = self._accrue(as_of, self._balance)
        posted = money(self._accrued_since_last_post + line_interest)

        self._balance += posted
        self._last_date = as_of
        self._accrued_since_last_post = Decimal("0")

        row = LedgerRow(
            date=as_of,
            code="Int.",
            interest_posted=posted,
            total_balance=self._balance,
            accrued_line_interest=line_interest,
        )
        self._rows.append(row)
        return row

    def run(self, transactions: list[Transaction], quarter_closes: list[date]) -> list[LedgerRow]:
        """Interleave transactions and quarter-closes in date order and post
        them in sequence. Convenience for building a full passbook from two
        separate inputs (deposits/withdrawals vs. the fixed quarterly
        schedule) without the caller hand-merging them."""
        events: list[tuple[date, int, object]] = []
        for i, t in enumerate(transactions):
            events.append((t.txn_date, 0, t))
        for i, q in enumerate(quarter_closes):
            events.append((q, 1, q))  # quarter-close sorts after same-day deposits
        events.sort(key=lambda e: (e[0], e[1]))

        for _, kind, payload in events:
            if kind == 0:
                self.post_transaction(payload)  # type: ignore[arg-type]
            else:
                self.post_quarter_close(payload)  # type: ignore[arg-type]
        return self._rows

    @property
    def rows(self) -> list[LedgerRow]:
        return list(self._rows)

    @property
    def balance(self) -> Decimal:
        return self._balance


def render_passbook(rows: list[LedgerRow]) -> list[dict]:
    """Table-rendering function: produces the member passbook breakdown as
    plain dicts with 2-decimal-formatted strings, ready to hand to a
    frontend/template. Null-safe against rows with no date (defensive; the
    engine never emits one, but callers may filter/trim lists upstream)."""

    def fmt(value: Optional[Decimal]) -> str:
        return "" if value is None else f"{money(value):.2f}"

    out = []
    for row in rows:
        if row is None or row.date is None:
            continue
        out.append(
            {
                "date": row.date.isoformat(),
                "code": row.code,
                "withdrawals": fmt(row.withdrawal),
                "interest": fmt(row.interest_posted),
                "deposits": fmt(row.deposit),
                "total_balance": fmt(row.total_balance),
                "accrued_line_interest": fmt(row.accrued_line_interest),
            }
        )
    return out
